--AGGREGATE WINDOW FUNCTION 

--1) RUNNING TOTAL  WITH PARTITION(SUM FUNCTION)
SELECT *,
		SUM(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH ) AS RUNNING_TOTAL
FROM SALES;

--RUNNING TOTAL WITHOUT PARTITION (SUM FUNCTION)
SELECT *,
       SUM(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;




--2) AVERAGE TOTAL WITH PARTITION WITH (USING AVG FUNCTION )
SELECT *,
     AVG(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH)::DECIMAL(10,2) AS AVG_TOTAL 
FROM SALES;

-- WITHOUT PARTITION
SELECT *,
       AVG(SALES) OVER(ORDER BY MONTH , SALESPERSON)::DECIMAL(10,2) AS RUNNING_TOTAL 
FROM SALES ;




-- 3). MAX VALUE(MAX FUNCTION)
SELECT *,
		MAX(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH) AS MAX_VALUE
FROM SALES;

--WITHOUT PARTITON 
SELECT *,
       MAX(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;




-- 4) MIN VALUE (MIN FUNCTION)
SELECT *,
       MIN(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH )AS MIN_VALUE
FROM SALES;


--WITHOUT PARTITON 
SELECT *,
       MIN(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;




 ## --  ANALYTICAL FUNCTION

-- 1) LAG() FUNCTION
--    DIFFRENCE B/W CURRENT AND PREVIUS MONTH WITH PARTITION 

SELECT * FROM SALES;

SELECT SALESPERSON, MONTH , SALES,
 		LAG(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH DESC ) AS PREVIUS_MONTH_SALES ,
		SALES - LAG(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH DESC) AS SALES_CHANGE 
FROM SALES;



--    DIFFRENCE B/W CURRENT AND PREVIUS MONTH WITHOUT PARTITION 

SELECT SALESPERSON , MONTH, SALES,
 		LAG(SALES) OVER (ORDER BY MONTH DESC ) AS PREVIUS_MONTH_SALES,
		SALES - LAG(SALES) OVER(ORDER BY MONTH DESC) AS SALES_CHANGE
FROM SALES;




-- 2) LEAD() FUNCTION
--    DIFFRENCE B/W CURRENT AND NEXT MONTH WITH PARTITION 

SELECT SALESPERSON , MONTH , SALES, 
		LEAD(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH DESC) AS NEXT_MONTH_SALES,
		LEAD(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH DESC) AS SALES_CHANGE
FROM SALES ;


--    DIFFRENCE B/W CURRENT AND NEXT MONTH WITH PARTITION 

SELECT SALESPERSON, MONTH, SALES,
		LEAD(SALES) OVER( ORDER BY MONTH DESC ) AS NEXT_MONTH_SALES,
		LEAD(SALES) OVER (ORDER BY MONTH DESC ) - SALES AS SALES_CHANGE
FROM SALES ;


--FIRST VALUE() FUNCTION : 
 --    IT SHOW FIRST ROW OF VLAUE IN EACH DEPARTMENT  ( WITH PARTITION)

 SELECT SALESPERSON, MONTH , SALES,
      FIRST_VALUE(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH DESC) AS STARTING_VALUE
 FROM SALES;

 -- WITHOUT PARTITION (IT SHOW ONLY ONE VALUE OF FIRST ROW)
 SELECT SALESPERSON, MONTH, SALES,
      FIRST_VALUE(SALES) OVER( ORDER BY MONTH DESC) AS START_VALUE
 FROM SALES;

 --LAST VALUE() FUNCTION 
  -- IT SHOW LAST ROW OF VLAUE IN EACH DEPARTMENT  ( WITH PARTITION)

SELECT SALESPERSON, MONTH, SALES,
       LAST_VALUE(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH DESC 
	   ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
	   ) AS ENDING_VALUE
FROM SALES;



-- WITHOUT PARTITION 
SELECT SALESPERSON, MONTH, SALES,
  		LAST_VALUE(SALES) OVER (ORDER BY MONTH DESC
	     ) AS END_VALUE
FROM SALES;




-- RANKING WITH PARTITION 
SELECT * FROM SALES;

SELECT SALESPERSON, MONTH , SALES,
		RANK() OVER(PARTITION BY SALESPERSON ORDER BY SALES DESC ) AS RANKING
FROM SALES;
