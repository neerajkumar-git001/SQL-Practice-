--AGGREGATE WINDOW FUNCTION 

--1) RUNNING TOTAL  WITH PARTITION(SUM FUNCTION)
SELECT *,
		SUM(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH ) AS RUNNING_TOTAL
FROM SALES;



--RUNNING TOTAL WITHOUT PARTITION (SUM FUNCTION)
SELECT *,
       SUM(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;


--2) AVERAGE TOTAL WITH PARTITION WITH (USING AVG FUNCTION )
SELECT *,
     AVG(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH)::DECIMAL(10,2) AS AVG_TOTAL 
FROM SALES;





-- 3). MAX VALUE(MAX FUNCTION)
SELECT *,
		MAX(SALES) OVER (PARTITION BY SALESPERSON ORDER BY MONTH) AS MAX_VALUE
FROM SALES;

--WITHOUT PARTITON 
SELECT *,
       MAX(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;




-- 4) MIN VALUE (MIN FUNCTION)
SELECT *,
       MIN(SALES) OVER(PARTITION BY SALESPERSON ORDER BY MONTH )AS MIN_VALUE
FROM SALES;


--WITHOUT PARTITON 
SELECT *,
       MIN(SALES) OVER(ORDER BY MONTH , SALESPERSON) AS RUNNING_TOTAL 
FROM SALES ;
