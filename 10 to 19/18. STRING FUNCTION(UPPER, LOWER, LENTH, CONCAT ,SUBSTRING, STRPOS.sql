-- String Function (upper, lower, lenth, concat, replace ,substring, strpos)

select *  from Sales_data;


-- use upper function 
SELECT CUSTOMER_NAME , UPPER(CUSTOMER_NAME)
FROM SALES_DATA;



-- USE LOWER FUNCTION 
SELECT SUB_CATEGORY, LOWER(SUB_CATEGORY)
FROM SALES_DATA;

SELECT LOWER(PRODUCT_ID)                 --DONE
FROM SALES_DATA;

-- USE LENGTH FUNCTION 
SELECT CUSTOMER_NAME, LENGTH(CUSTOMER_NAME)
FROM SALES_DATA;

SELECT ORDER_ID, LENGTH(ORDER_ID)
FROM SALES_DATA;

SELECT POSTAL_CODE, LENGTH(POSTAL_CODE)           -- NOT RUN
FROM SALES_DATA;

-- USE CONCAT FUNCTION 
SELECT CUSTOMER_NAME, SHIP_MODE, CONCAT(CUSTOMER_NAME, ' - ', SHIP_MODE)
FROM SALES_DATA;


SELECT CUSTOMER_ID, SEGMENT , CONCAT(CUSTOMER_ID, ' - ', SEGMENT)
FROM SALES_DATA;


-- USE REPLACE FUNCTION
SELECT REGION , REPLACE(REGION, 'Central', 'North')
FROM SALES_DATA;

SELECT STATE, REPLACE(STATE, 'Texas', 'Virginia')
FROM SALES_DATA;

SELECT POSTAL_CODE , REPLACE(POSTAL_CODE, '77095', '77000')        -- NOT RUN 
FROM SALES_DATA;

--USE SUBSTRING FUNCTION 
SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, 1,7)     --(1 TO 7 LENGTH OF DIGIT)
FROM SALES_DATA;

SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, 7, 14)   -- (7 TO 14 LENGTH)
FROM SALES_DATA;

SELECT ORDER_DATE, SUBSTRING(ORDER_DATE, 1 , 5)          -- NOT WORK IN DATE 
FROM SALES_DATA;


-- USE STRPOS
SELECT CUSTOMER_NAME, STRPOS(CUSTOMER_NAME,' ')
FROM SALES_DATA;

SELECT CUSTOMER_NAME, STRPOS(CUSTOMER_NAME, 'l')
FROM SALES_DATA;


--GET SEPRATE FIRST NAME FOR CUSTOMER NAME
SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, 1, STRPOS(CUSTOMER_NAME, ' ')) AS FIRST_NAME
FROM SALES_DATA;

--GET SEPRATE LAST NAME FOR CUSTOMER NAME 
SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, STRPOS(CUSTOMER_NAME, ' ')) AS LAST_NAME
FROM SALES_DATA;
--OR 
SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, STRPOS(CUSTOMER_NAME, ' '),LENGTH(CUSTOMER_NAME)) AS LAST_NAME
FROM SALES_DATA;


-- SEPRATE COLUMN FIRST_NAME AND LAST_NAME 
SELECT CUSTOMER_NAME, SUBSTRING(CUSTOMER_NAME, 1, STRPOS(CUSTOMER_NAME, ' ')) AS FIRST_NAME,
SUBSTRING(CUSTOMER_NAME, STRPOS(CUSTOMER_NAME, ' '))
FROM SALES_DATA;