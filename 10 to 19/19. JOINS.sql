-- 2) IMPORT PRODUCT FILE

DROP TABLE IF EXISTS PRODUCT ;
CREATE TABLE IF NOT EXISTS PRODUCT(
  Customer_id	VARCHAR(7) PRIMARY KEY ,
  Product	VARCHAR(20), 
  Price	INT 

);
SELECT * FROM PRODUCT;




-- 3)GET SPECIFIC COLUMN 
SELECT C.CUSTOMER_NAME , P.PRODUCT , P.PRICE
FROM CUSTOMER_DATA C
INNER JOIN PRODUCT P
USING(CUSTOMER_ID);


-- 4) ALL DATA PRINT
SELECT *
FROM CUSTOMER_DATA C
INNER JOIN PRODUCT P
USING(CUSTOMER_ID);




SELECT *
FROM CUSTOMER_DATA C
INNER JOIN PRODUCT P
ON C.CUSTOMER_ID = P.CUSTOMER_ID;



-- LEFT JOIN 
SELECT *
FROM CUSTOMER_DATA
LEFT JOIN PRODUCT 
ON CUSTOMER_DATA.CUSTOMER_ID = PRODUCT.CUSTOMER_ID;


-- RIGHT JOIN 
SELECT *
FROM CUSTOMER_DATA AS C
RIGHT JOIN PRODUCT AS P
ON C.CUSTOMER_ID = P.CUSTOMER_ID;


SELECT *
FROM CUSTOMER_DATA AS C
RIGHT JOIN PRODUCT AS P
USING(CUSTOMER_ID);



-- FULL OUTER JOIN 
SELECT * 
FROM CUSTOMER_DATA AS C
FULL OUTER JOIN PRODUCT AS P
ON C.CUSTOMER_ID = P.CUSTOMER_ID;

SELECT *
FROM CUSTOMER_DATA 
