-- 7) find out all the movie starting by Aamir Khan 
SELECT *
FROM MOVIE_RATINGS
WHERE UPPER(STAR1) ='AAMIR KHAN'
OR UPPER(STAR2) = 'AAMIR KHAN'
OR UPPER(STAR3) = 'AAMIR KHAN'
OR UPPER(STAR4) = 'AAMIR KHAN';

-- 8) HOW MUCH MONEY DID AAMIR KHAN EARN ?
SELECT SUM(GROSS)
FROM MOVIE_RATINGS
WHERE UPPER(STAR1) ='AAMIR KHAN'
OR UPPER(STAR2) = 'AAMIR KHAN'
OR UPPER(STAR3) = 'AAMIR KHAN'
OR UPPER(STAR4) = 'AAMIR KHAN';

