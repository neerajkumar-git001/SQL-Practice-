-- Date function (EXTRACT AND TO_CHAR, AGE FUNCTION )


SELECT * FROM SALES_DATA;

-- extarct month number from date 
SELECT EXTRACT(MONTH FROM SHIP_DATE)
FROM SALES_DATA;


-- EXTRACT MONTH NAME 
SELECT TO_CHAR(SHIP_DATE, 'MONTH')
FROM SALES_DATA;


--- GET TOTAL SALES MONTH WISE 
SELECT TO_CHAR(SHIP_DATE, 'Month'), SUM(sales_$)
FROM SALES_DATA
GROUP BY TO_CHAR(SHIP_DATE, 'Month');






USE OF AGE FUNCTION

-- BIRTH DATE 
SELECT AGE(CURRENT_DATE , '29-10-2006')


-- INTERVAL DAY BETWEEN SHIP DATE AND ORDER DATE 

SELECT SHIP_DATE, ORDER_DATE, AGE(SHIP_DATE, ORDER_DATE) AS INTERVAL_DATE 
FROM SALES_DATA ;

